-- Basic Calculations
add = 8 + 2
subtract = 8 - 2
multiply = 8 * 2
whole_number_divide = 8 `div` 2
ordinary_divide = 8 / 3
modulus = 8 `mod` 2

-- Comparison Operators
equal = (5 == 5)
not_equal = (5 /= 8)
greater_than_or_equal = (5 >= 3)
less_than_or_equal = (5 <= 7)

-- Boolean Operators
and_ = (5 > 3 && 3 < 5)
or_ = ( 5 > 3 || 3 > 5)
not_ = (not True)

