{-
    Simple functions:
    Syntax
        functionName paramete1 parameter... = result
-}

-- simple function called 'multiply'
multiply x = x * 3

-- function with multiples parameters
rectangleArea width height = width * height


{-
    Type Signature functions : contains type of input and output
    Sytax 
        functionName :: InputType1 InputType... -> OutputType1
-}

-- example
double :: Int -> Int
double x = x * 2


